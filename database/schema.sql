CREATE TABLE IF NOT EXISTS users (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(100) NOT NULL,
 email VARCHAR(190) NOT NULL UNIQUE,
 password VARCHAR(255) NOT NULL,
 role ENUM('admin','dispatcher','driver') NOT NULL DEFAULT 'admin',
 driver_id INT UNSIGNED NULL,
 active TINYINT NOT NULL DEFAULT 1,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS customers (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(100) NOT NULL,
 phone VARCHAR(25) NOT NULL,
 address VARCHAR(255) NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS drivers (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(100) NOT NULL,
 phone VARCHAR(25) NOT NULL,
 vehicle VARCHAR(30) NOT NULL,
 active TINYINT NOT NULL DEFAULT 1,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS orders (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 code VARCHAR(30) NOT NULL UNIQUE,
 customer_id INT UNSIGNED NOT NULL,
 driver_id INT UNSIGNED NULL,
 recipient_name VARCHAR(100) NOT NULL,
 recipient_phone VARCHAR(25) NOT NULL,
 pickup_address VARCHAR(255) NOT NULL,
 delivery_address VARCHAR(255) NOT NULL,
 package_name VARCHAR(150) NOT NULL,
 weight DECIMAL(8,2) NOT NULL DEFAULT 0,
 cod DECIMAL(14,0) NOT NULL DEFAULT 0,
 fee DECIMAL(14,0) NOT NULL DEFAULT 0,
 cod_settled TINYINT NOT NULL DEFAULT 0,
 status ENUM('pending','picked','shipping','delivered','failed','cancelled') NOT NULL DEFAULT 'pending',
 note TEXT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 delivered_at DATETIME NULL,
 FOREIGN KEY (customer_id) REFERENCES customers(id),
 FOREIGN KEY (driver_id) REFERENCES drivers(id),
 INDEX idx_status_created(status,created_at), INDEX idx_created(created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS order_events (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 order_id INT UNSIGNED NOT NULL,
 status VARCHAR(20) NOT NULL,
 note VARCHAR(500) NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (order_id) REFERENCES orders(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
